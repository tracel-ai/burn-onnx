    #[test]
    fn maxpool3d() {
        // Expected values from maxpool3d.py (ONNX reference, identical in ONNX Runtime):
        // asymmetric pads + ceil_mode + dilation, the Indices output in row-major and
        // column-major order, and SAME_UPPER.
        let device = Default::default();
        let model =
            maxpool3d::Model::from_file(concat!(env!("OUT_DIR"), "/model/maxpool3d.bpk"), &device);

        let (y, y_row, y_indices_row, y_col, y_indices_col, y_same) =
            model.forward(input(&MAXPOOL_INPUT));

        y.to_data()
            .assert_eq(&TensorData::new(MAXPOOL_Y.to_vec(), MAXPOOL_Y_SHAPE), false);
        y_row
            .to_data()
            .assert_eq(&TensorData::new(MAXPOOL_Y.to_vec(), MAXPOOL_Y_SHAPE), false);
        y_col
            .to_data()
            .assert_eq(&TensorData::new(MAXPOOL_Y.to_vec(), MAXPOOL_Y_SHAPE), false);
        y_indices_row.to_data().assert_eq(
            &TensorData::new(MAXPOOL_INDICES_ROW.to_vec(), MAXPOOL_Y_SHAPE),
            false,
        );
        y_indices_col.to_data().assert_eq(
            &TensorData::new(MAXPOOL_INDICES_COL.to_vec(), MAXPOOL_Y_SHAPE),
            false,
        );
        y_same.to_data().assert_eq(
            &TensorData::new(MAXPOOL_SAME.to_vec(), MAXPOOL_SAME_SHAPE),
            false,
        );
    }

    #[test]
    fn avgpool3d() {
        // Expected values from avgpool3d.py (ONNX reference, checked against ONNX Runtime).
        // The input dims are dynamic, so SAME_LOWER's pads are computed at run time.
        let device = Default::default();
        let model =
            avgpool3d::Model::from_file(concat!(env!("OUT_DIR"), "/model/avgpool3d.bpk"), &device);

        let (y_include, y_exclude, y_same) = model.forward(input(&AVGPOOL_INPUT));

        let tolerance = Tolerance::absolute(1e-5);
        y_include.to_data().assert_approx_eq::<f32>(
            &TensorData::new(AVGPOOL_INCLUDE.to_vec(), AVGPOOL_SHAPE),
            tolerance,
        );
        y_exclude.to_data().assert_approx_eq::<f32>(
            &TensorData::new(AVGPOOL_EXCLUDE.to_vec(), AVGPOOL_SHAPE),
            tolerance,
        );
        y_same.to_data().assert_approx_eq::<f32>(
            &TensorData::new(AVGPOOL_SAME.to_vec(), AVGPOOL_SAME_SHAPE),
            tolerance,
        );
    }

    #[test]
    fn maxpool3d_int() {
        // Expected values from maxpool3d_int.py (ONNX Runtime, identical to a brute-force
        // reference): int8 and uint8 inputs are pooled in their own dtype, and the uint8
        // pool's Indices output is an intermediate value without precomputed type metadata.
        let device = Default::default();
        let model = maxpool3d_int::Model::from_file(
            concat!(env!("OUT_DIR"), "/model/maxpool3d_int.bpk"),
            &device,
        );
        let x_i8 = Tensor::<5, Int>::from_data(
            TensorData::new(INT_I8_INPUT.to_vec(), INT_INPUT_SHAPE),
            (&device, DType::I8),
        );
        let x_u8 = Tensor::<5, Int>::from_data(
            TensorData::new(INT_U8_INPUT.to_vec(), INT_INPUT_SHAPE),
            (&device, DType::U8),
        );

        let (y_i8, y_u8, y_u8_neg_indices) = model.forward(x_i8, x_u8);

        assert_eq!(y_i8.dtype(), DType::I8);
        assert_eq!(y_u8.dtype(), DType::U8);
        y_i8.to_data()
            .assert_eq(&TensorData::new(INT_Y_I8.to_vec(), INT_INPUT_SHAPE), true);
        y_u8.to_data().assert_eq(
            &TensorData::new(INT_Y_U8.to_vec(), INT_U8_OUTPUT_SHAPE),
            true,
        );
        y_u8_neg_indices.to_data().assert_eq(
            &TensorData::new(INT_U8_NEG_INDICES.to_vec(), INT_U8_OUTPUT_SHAPE),
            true,
        );
    }

