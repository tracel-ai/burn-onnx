# /// script
# dependencies = ["onnx==1.19.0", "numpy"]
# ///
from pathlib import Path
import numpy as np
import onnx
from onnx import helper as h, numpy_helper as nh, TensorProto as T
from onnx.reference import ReferenceEvaluator
np.random.seed(42)
root=Path(__file__).parent
lines=['// Generated by convolution.py using ONNX ReferenceEvaluator.']
for n in [1,2,3]:
    spatial=[4]*n
    x=(np.arange(4*np.prod(spatial))%17).astype(np.uint8).reshape([1,4]+spatial)
    w=(np.arange(4*2*2**n)%9-4).astype(np.int8).reshape([4,2]+[2]*n)
    arrays={'w':w,'xz':np.array(7,np.uint8),'wz':np.array([-2,1,0,-1],np.int8),'xs':np.array(.5,np.float32),'ws':np.array([.25,.5,.75,1.],np.float32),'ys':np.array(.25,np.float32),'yz':np.array(128,np.uint8),'bias':np.array([-3,1,2,-4],np.int32)}
    attrs=dict(group=2,strides=[2]*n,dilations=[2]*n,pads=[1]*n+[0]*n)
    nodes=[h.make_node('ConvInteger',['x','w','xz','wz'],['integer'],**attrs),h.make_node('QLinearConv',['x','xs','xz','w','ws','wz','ys','yz','bias'],['quantized'],**attrs)]
    out_shape=[1,4]+[2]*n
    model=h.make_model(h.make_graph(nodes,'conv',[h.make_tensor_value_info('x',T.UINT8,list(x.shape))],[h.make_tensor_value_info('integer',T.INT32,out_shape),h.make_tensor_value_info('quantized',T.UINT8,out_shape)],[nh.from_array(v,k) for k,v in arrays.items()]),opset_imports=[h.make_opsetid('',10)])
    onnx.checker.check_model(model)
    # ONNX 1.19 ConvInteger fails on vector zero points, and QLinearConv's
    # per-channel scale expansion is hardcoded to 2D. Evaluate the equivalent
    # centered Conv; these small integral sums are exactly representable in f32.
    centered_w = w.astype(np.float32) - arrays['wz'].reshape([4]+[1]*(n+1))
    ref=h.make_model(h.make_graph([h.make_node('Conv',['centered','weight'],['sum'],**attrs)],'reference',[h.make_tensor_value_info('centered',T.FLOAT,list(x.shape))],[h.make_tensor_value_info('sum',T.FLOAT,out_shape)],[nh.from_array(centered_w,'weight')]),opset_imports=[h.make_opsetid('',11)])
    accum=ReferenceEvaluator(ref).run(None,{'centered':x.astype(np.float32)-7})[0].astype(np.int32)
    channel_shape=[1,4]+[1]*n
    quant=np.clip(np.rint((accum+arrays['bias'].reshape(channel_shape))*(arrays['xs']*arrays['ws']/arrays['ys']).reshape(channel_shape))+arrays['yz'],0,255).astype(np.uint8)
    result=[accum,quant]
    onnx.save(model,root/f'quant_conv{n}d.onnx')
    for label,data,typ in [('INPUT',x,'u8'),('INTEGER',result[0],'i32'),('QUANTIZED',result[1],'u8')]:
        values=data.flatten().tolist()
        lines.append(f'const {label}_{n}D: [{typ}; {len(values)}] = {values};')
(root/'convolution_data.rs').write_text('\n'.join(lines)+'\n')
